static void usage(const char *prog)
{
    fprintf(stderr,
            "Usage: %s --tree <path> --storage <checkpoint> --output <file> [options]\n"
            "\n"
            "Required:\n"
            "  --tree <path>            Tree definition used during the run\n"
            "  --storage <path>         CFR checkpoint to load (from mpf_run_with_metrics)\n"
            "  --output <path>          Destination file for the export\n"
            "\n"
            "Options:\n"
            "  --format <json|csv>      Output format (default: json)\n"
            "  --street <name>          Street filter (prefop, flop, turn, river, showdown)\n"
            "  --player <index>         Acting player filter\n"
            "  --node-prefix <prefix>   Export only nodes whose id starts with prefix\n"
            "  --include-unvisited      Include nodes that were never visited\n"
            "  --no-combos              Skip per-combo breakdown in the export\n"
            "  --no-pretty              Disable pretty-printing for JSON output\n"
            "  --node-map <path>        Node key map generated by mpf_run_with_metrics\n"
            "  --help                   Show this message\n",
            prog);
}

static int apply_node_map_csv(mpf_tree_def_t *tree, const char *path)
{
    if (!tree || !path)
        return -1;
    FILE *f = fopen(path, "r");
    if (!f)
        return -1;
    char line[512];
    if (!fgets(line, sizeof(line), f))
    {
        fclose(f);
        return -1;
    }
    while (fgets(line, sizeof(line), f))
    {
        char *comma = strchr(line, ',');
        if (!comma)
            continue;
        *comma = '\0';
        char *id = line;
        char *key_str = comma + 1;
        size_t len = strlen(key_str);
        while (len > 0 && (key_str[len - 1] == '\n' || key_str[len - 1] == '\r'))
            key_str[--len] = '\0';
        uint64_t key = strtoull(key_str, NULL, 0);
        for (int i = 0; i < tree->node_count; ++i)
        {
            mpf_tree_node_t *node = &tree->nodes[i];
            if (node->id && strcmp(node->id, id) == 0)
            {
                node->state_key = key;
                break;
            }
        }
    }
    fclose(f);
    return 0;
}

static int parse_int(const char *arg, int *out)
{
    char *end = NULL;
    long v = strtol(arg, &end, 10);
    if (!end || *end != '\0')
        return 0;
    *out = (int)v;
    return 1;
}

static char *load_file(const char *path, size_t *out_len)
{
    FILE *f = fopen(path, "rb");
    if (!f)
        return NULL;
    if (fseek(f, 0, SEEK_END) != 0)
    {
        fclose(f);
        return NULL;
    }
    long len = ftell(f);
    if (len < 0)
    {
        fclose(f);
        return NULL;
    }
    if (fseek(f, 0, SEEK_SET) != 0)
    {
        fclose(f);
        return NULL;
    }
    char *buf = (char *)malloc((size_t)len + 1);
    if (!buf)
    {
        fclose(f);
        return NULL;
    }
    size_t read_bytes = fread(buf, 1, (size_t)len, f);
    fclose(f);
    if (read_bytes != (size_t)len)
    {
        free(buf);
        return NULL;
    }
    buf[len] = '\0';
    if (out_len)
        *out_len = (size_t)len;
    return buf;
}

static int parse_street(const char *value, mpf_street_t *street)
{
    if (strcasecmp(value, "preflop") == 0)
        *street = MPF_STREET_PREFLOP;
    else if (strcasecmp(value, "flop") == 0)
        *street = MPF_STREET_FLOP;
    else if (strcasecmp(value, "turn") == 0)
        *street = MPF_STREET_TURN;
    else if (strcasecmp(value, "river") == 0)
        *street = MPF_STREET_RIVER;
    else if (strcasecmp(value, "showdown") == 0)
        *street = MPF_STREET_SHOWDOWN;
    else
        return 0;
    return 1;
}

int main(int argc, char **argv)
{
    const char *tree_path = NULL;
    const char *storage_path = NULL;
    const char *output_path = NULL;
    const char *format_str = "json";
    int include_unvisited = 0;
    int include_combos = 1;
    int pretty = 1;
    int acting_player_filter = 0;
    int acting_player_value = -1;
    mpf_street_t street_value = MPF_STREET_PREFLOP;
    int street_filter = 0;
    const char *node_prefix = NULL;
    const char *node_map_path = NULL;

    for (int i = 1; i < argc; ++i)
    {
        if (strcmp(argv[i], "--tree") == 0 && i + 1 < argc)
        {
            tree_path = argv[++i];
        }
        else if (strcmp(argv[i], "--storage") == 0 && i + 1 < argc)
        {
            storage_path = argv[++i];
        }
        else if (strcmp(argv[i], "--output") == 0 && i + 1 < argc)
        {
            output_path = argv[++i];
        }
        else if (strcmp(argv[i], "--format") == 0 && i + 1 < argc)
        {
            format_str = argv[++i];
        }
        else if (strcmp(argv[i], "--street") == 0 && i + 1 < argc)
        {
            if (!parse_street(argv[++i], &street_value))
            {
                fprintf(stderr, "Unknown street name\n");
                return 1;
            }
            street_filter = 1;
        }
        else if (strcmp(argv[i], "--player") == 0 && i + 1 < argc)
        {
            if (!parse_int(argv[++i], &acting_player_value) || acting_player_value < 0)
            {
                fprintf(stderr, "Invalid player index\n");
                return 1;
            }
            acting_player_filter = 1;
        }
        else if (strcmp(argv[i], "--node-prefix") == 0 && i + 1 < argc)
        {
            node_prefix = argv[++i];
        }
        else if (strcmp(argv[i], "--include-unvisited") == 0)
        {
            include_unvisited = 1;
        }
        else if (strcmp(argv[i], "--no-combos") == 0)
        {
            include_combos = 0;
        }
        else if (strcmp(argv[i], "--no-pretty") == 0)
        {
            pretty = 0;
        }
        else if (strcmp(argv[i], "--node-map") == 0 && i + 1 < argc)
        {
            node_map_path = argv[++i];
        }
        else if (strcmp(argv[i], "--help") == 0)
        {
            usage(argv[0]);
            return 0;
        }
        else
        {
            fprintf(stderr, "Unknown option: %s\n", argv[i]);
            usage(argv[0]);
            return 1;
        }
    }

    if (!tree_path || !storage_path || !output_path || !node_map_path)
    {
        usage(argv[0]);
        return 1;
    }

    mpf_export_options_t opts;
    memset(&opts, 0, sizeof(opts));
    opts.include_combos = include_combos;
    opts.pretty = pretty;
    opts.path = output_path;
    opts.filter.include_unvisited = include_unvisited;
    opts.filter.street_filter_enabled = street_filter;
    opts.filter.street = street_value;
    opts.filter.acting_player_filter_enabled = acting_player_filter;
    opts.filter.acting_player = acting_player_value;
    opts.filter.node_id_prefix = node_prefix;

    if (strcasecmp(format_str, "json") == 0)
    {
        opts.format = MPF_EXPORT_FORMAT_JSON;
    }
    else if (strcasecmp(format_str, "csv") == 0)
    {
        opts.format = MPF_EXPORT_FORMAT_CSV;
        if (pretty)
            opts.pretty = 0; /* not relevant for CSV */
    }
    else
    {
        fprintf(stderr, "Unsupported format: %s\n", format_str);
        return 1;
    }

    size_t json_len = 0;
    char *json_data = load_file(tree_path, &json_len);
    if (!json_data)
    {
        fprintf(stderr, "Failed to read tree file '%s': %s\n", tree_path, strerror(errno));
        return 1;
    }

    mpf_tree_error_t tree_err = {0};
    mpf_tree_def_t *tree = mpf_tree_load_json(json_data, json_len, &tree_err);
    free(json_data);
    if (!tree)
    {
        fprintf(stderr, "Tree load error: %s\n", tree_err.message[0] ? tree_err.message : "unknown");
        return 1;
    }
    if (!mpf_tree_validate(tree, &tree_err))
    {
        fprintf(stderr, "Tree validation error: %s\n", tree_err.message[0] ? tree_err.message : "unknown");
        mpf_tree_free(tree);
        return 1;
    }

    if (apply_node_map_csv(tree, node_map_path) != 0)
    {
        fprintf(stderr, "Failed to read node map '%s': %s\n", node_map_path, strerror(errno));
        mpf_tree_free(tree);
        return 1;
    }

    cfr_storage_t *storage = cfr_storage_create();
    if (!storage)
    {
        fprintf(stderr, "Failed to allocate CFR storage\n");
        mpf_tree_free(tree);
        return 1;
    }

    uint64_t restored_iteration = 0;
    if (cfr_storage_load_checkpoint(storage, storage_path, &restored_iteration) != 0)
    {
        fprintf(stderr, "Failed to load storage '%s': %s\n", storage_path, strerror(errno));
        cfr_storage_destroy(storage);
        mpf_tree_free(tree);
        return 1;
    }

    if (mpf_export_node_results(tree, storage, &opts) != 0)
    {
        fprintf(stderr, "Export failed for '%s'\n", output_path);
        cfr_storage_destroy(storage);
        mpf_tree_free(tree);
        return 1;
    }

    printf("Exported results to %s (iteration %" PRIu64 ")\n",
           output_path, restored_iteration);

    cfr_storage_destroy(storage);
    mpf_tree_free(tree);
    return 0;
}
